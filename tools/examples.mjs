import {mkdir,writeFile} from 'node:fs/promises';
import {createTeam,MISSIONS,setRule} from '../src/domain.js';
import {makeKitFiles,zipFiles} from '../src/export.js';
import {runSuite} from '../src/evaluator.js';
const root=new URL('../examples/',import.meta.url);await mkdir(root,{recursive:true});
for(const m of MISSIONS){const team=createTeam(m.mission,m.id);await writeFile(new URL(m.id+'-baseline.json',root),JSON.stringify(team,null,2)+'\n');}
let team=createTeam(MISSIONS[0].mission);team=setRule(team,'timestamps',true);
const files=makeKitFiles(team,runSuite(team));await writeFile(new URL('release-monitor-kit.zip',root),zipFiles(files));
await writeFile(new URL('README.md',root),'# Reproducible examples\n\nBaseline JSON files are generated by the same template logic as the app. release-monitor-kit.zip is a local Node-generated example with the timestamp repair applied; it is NOT the separate browser-download evidence. Regenerate with `node tools/examples.mjs`.\n');
console.log('Three baseline examples and a real generated kit saved.');
